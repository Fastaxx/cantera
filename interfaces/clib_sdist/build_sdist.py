"""Source distribution of the shared Cantera library with its C API (CLib).

The archive is self-contained: the CLib sources and the Julia bindings are
already generated, so building it only needs CMake, a C++20 compiler and the
third-party libraries. It is what the Yggdrasil recipe for `Cantera_jll` builds.

Run from the root of the repository after `scons build`, which generates the CLib
and the Julia bindings.
"""

from pathlib import Path
import argparse
import importlib.util
import shutil
import sys

# Reuse the helpers of the Python sdist (same file name, so load it by path).
_spec = importlib.util.spec_from_file_location(
    "python_sdist", Path(__file__).parents[1] / "python_sdist" / "build_sdist.py")
_python_sdist = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_python_sdist)
do_configure_substitution = _python_sdist.do_configure_substitution
replace_git_hash = _python_sdist.replace_git_hash


def main(
    source_directory: Path,
    target_directory: Path,
    git_commit: str,
    cantera_version: str,
    cantera_short_version: str,
    archive: bool = False,
) -> Path:
    clib_source = source_directory / "interfaces" / "clib"
    julia_source = source_directory / "interfaces" / "julia" / "src" / "generated"
    for generated in (clib_source / "src" / "ct.cpp", julia_source / "_manifest.jl"):
        if not generated.exists():
            raise FileNotFoundError(
                f"{generated} is missing: run 'scons build' first to generate the "
                "CLib and the Julia bindings")

    if target_directory.exists():
        shutil.rmtree(target_directory)

    # Library sources, without the Python and Fortran interfaces or the
    # static-library indicator.
    src_target = target_directory / "src"
    shutil.copytree(
        source_directory / "src",
        src_target,
        ignore=shutil.ignore_patterns(
            "fortran",
            "pch",
            "global.cpp",
            "SCons*",
            "canteraStatic.cpp",
            "PythonExtensionManager.cpp",
            "pythonShim.cpp",
        ),
        dirs_exist_ok=True,
    )
    global_cpp = Path("base", "global.cpp")
    replace_git_hash(source_directory / "src" / global_cpp, src_target / global_cpp,
                     git_commit)

    # Public headers. config.h is generated by CMake from config.h.in, and the
    # bundled third-party headers in `ext` are replaced by the system libraries.
    include_target = target_directory / "include"
    shutil.copytree(
        source_directory / "include",
        include_target,
        ignore=shutil.ignore_patterns("ext", "cython", "config.h", "config.h.in"),
        dirs_exist_ok=True,
    )
    config_h_in = Path("cantera", "base", "config.h.in")
    (include_target / config_h_in).write_text(
        do_configure_substitution(source_directory / "include" / config_h_in,
                                  cantera_version, cantera_short_version))

    # Generated CLib sources and headers.
    shutil.copytree(clib_source / "src", target_directory / "clib" / "src",
                    ignore=shutil.ignore_patterns("SCons*"), dirs_exist_ok=True)
    shutil.copytree(clib_source / "include", target_directory / "clib" / "include",
                    dirs_exist_ok=True)

    # Generated Julia bindings, installed next to the library.
    shutil.copytree(julia_source, target_directory / "julia" / "generated",
                    dirs_exist_ok=True)

    # Input files (gri30.yaml etc.), without the example data.
    shutil.copytree(source_directory / "data", target_directory / "data",
                    ignore=shutil.ignore_patterns("example_data"),
                    dirs_exist_ok=True)

    here = Path(__file__).parent
    shutil.copy2(here / "CMakeLists.txt", target_directory / "CMakeLists.txt")
    shutil.copy2(source_directory / "License.txt", target_directory / "License.txt")
    shutil.copy2(source_directory / "README.rst", target_directory / "README.rst")

    if not archive:
        return target_directory
    return Path(shutil.make_archive(str(target_directory), "gztar",
                                    root_dir=target_directory.parent,
                                    base_dir=target_directory.name))


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source_directory")
    parser.add_argument("target_directory")
    parser.add_argument("git_commit")
    parser.add_argument("cantera_version")
    parser.add_argument("cantera_short_version")
    parser.add_argument("--archive", action="store_true",
                        help="also create a .tar.gz archive of the target directory")
    return parser.parse_args(argv)


if __name__ == "__main__":
    args = parse_args(sys.argv[1:])
    out = main(Path(args.source_directory), Path(args.target_directory),
               args.git_commit, args.cantera_version, args.cantera_short_version,
               args.archive)
    print(out)
